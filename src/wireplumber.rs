//! System-wide input disabling through WirePlumber `node.disabled` rules.
//!
//! `~/.config/sound-checker/disabled.json` is the source of truth; the
//! WirePlumber drop-in is regenerated from it on every change.

use std::fs;
use std::io;
use std::path::PathBuf;
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};

const CONF_NAME: &str = "90-sound-checker.conf";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct DisabledEntry {
    pub node_name: String,
    pub device_name: Option<String>,
    pub description: String,
    pub bus: Option<String>,
    pub disabled_at: u64,
    /// A playback device rather than an input; absent in older state files.
    #[serde(default)]
    pub output: bool,
}

impl DisabledEntry {
    pub fn new(
        node_name: String,
        device_name: Option<String>,
        description: String,
        bus: Option<String>,
        output: bool,
    ) -> Self {
        let disabled_at = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |d| d.as_secs());
        DisabledEntry { node_name, device_name, description, bus, disabled_at, output }
    }

    fn is_bluetooth(&self) -> bool {
        self.bus.as_deref() == Some("bluetooth") || self.node_name.starts_with("bluez_")
    }
}

fn config_home() -> PathBuf {
    std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|p| p.is_absolute())
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))
        .unwrap_or_else(|| PathBuf::from(".config"))
}

fn state_path() -> PathBuf {
    config_home().join("sound-checker").join("disabled.json")
}

fn conf_path() -> PathBuf {
    config_home().join("wireplumber").join("wireplumber.conf.d").join(CONF_NAME)
}

pub fn load() -> Vec<DisabledEntry> {
    fs::read(state_path())
        .ok()
        .and_then(|b| serde_json::from_slice(&b).ok())
        .unwrap_or_default()
}

fn save(entries: &[DisabledEntry]) -> io::Result<()> {
    let path = state_path();
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    let json = serde_json::to_vec_pretty(entries).map_err(io::Error::other)?;
    fs::write(path, json)
}

/// Quote a string for a WirePlumber (SPA JSON) config value.
fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn rules(entries: &[&DisabledEntry]) -> String {
    let mut s = String::from("[\n");
    for e in entries {
        s.push_str(&format!(
            "  {{\n    matches = [ {{ node.name = {} }} ]\n    actions = {{ update-props = {{ node.disabled = true }} }}\n  }}\n",
            quote(&e.node_name)
        ));
    }
    s.push(']');
    s
}

/// The drop-in file contents, or `None` when nothing is disabled.
pub fn generate_config(entries: &[DisabledEntry]) -> Option<String> {
    if entries.is_empty() {
        return None;
    }
    let (bt, alsa): (Vec<&DisabledEntry>, Vec<&DisabledEntry>) =
        entries.iter().partition(|e| e.is_bluetooth());
    let mut out = String::from("# Generated by Linux Sound Checker. Edits are overwritten.\n");
    if !alsa.is_empty() {
        out.push_str(&format!("monitor.alsa.rules = {}\n", rules(&alsa)));
    }
    if !bt.is_empty() {
        out.push_str(&format!("monitor.bluez.rules = {}\n", rules(&bt)));
    }
    Some(out)
}

/// Persist `entries` and rewrite (or remove) the WirePlumber drop-in.
pub fn write_all(entries: &[DisabledEntry]) -> io::Result<()> {
    save(entries)?;
    let path = conf_path();
    match generate_config(entries) {
        Some(conf) => {
            if let Some(dir) = path.parent() {
                fs::create_dir_all(dir)?;
            }
            fs::write(path, conf)
        }
        None => match fs::remove_file(path) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        },
    }
}

/// Whether a `wireplumber` systemd user unit exists to restart.
pub fn can_restart() -> bool {
    Command::new("systemctl")
        .args(["--user", "cat", "wireplumber.service"])
        .output()
        .is_ok_and(|o| o.status.success())
}

/// MAC addresses of currently connected Bluetooth devices.
fn connected_bluetooth() -> Vec<String> {
    let Ok(out) = Command::new("bluetoothctl").args(["devices", "Connected"]).output() else {
        return Vec::new();
    };
    parse_devices(&String::from_utf8_lossy(&out.stdout))
}

fn parse_devices(text: &str) -> Vec<String> {
    text.lines()
        .filter_map(|l| l.strip_prefix("Device "))
        .filter_map(|l| l.split_whitespace().next())
        .map(str::to_string)
        .collect()
}

fn is_connected(mac: &str) -> bool {
    Command::new("bluetoothctl")
        .args(["info", mac])
        .output()
        .is_ok_and(|o| String::from_utf8_lossy(&o.stdout).contains("Connected: yes"))
}

fn pactl(args: &[&str]) -> String {
    Command::new("pactl")
        .args(args)
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default()
}

/// The default sink and source, read before WirePlumber restarts.
fn defaults() -> (String, String) {
    (pactl(&["get-default-sink"]), pactl(&["get-default-source"]))
}

/// A restarted WirePlumber re-picks its defaults and can bypass virtual
/// devices (e.g. EasyEffects), so put the previous ones back.
fn restore_defaults((sink, source): &(String, String)) {
    for (get, set, list, name) in [
        ("get-default-sink", "set-default-sink", "sinks", sink),
        ("get-default-source", "set-default-source", "sources", source),
    ] {
        let exists = pactl(&["list", "short", list]).lines().any(|l| l.split('\t').nth(1) == Some(name));
        if !name.is_empty() && exists && pactl(&[get]) != *name {
            pactl(&[set, name]);
        }
    }
}

/// Restart WirePlumber, which drops Bluetooth audio links, then reconnect the
/// devices that were connected before. Blocking; run off the main thread.
pub fn restart() -> Result<(), String> {
    let before = connected_bluetooth();
    let saved_defaults = defaults();
    let out = Command::new("systemctl")
        .args(["--user", "restart", "wireplumber.service"])
        .output()
        .map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).trim().to_string());
    }
    // Let it enumerate devices again before touching the defaults.
    std::thread::sleep(std::time::Duration::from_secs(2));
    restore_defaults(&saved_defaults);
    if !before.is_empty() {
        // Give devices a moment to come back by themselves first.
        std::thread::sleep(std::time::Duration::from_secs(1));
        for mac in before.iter().filter(|m| !is_connected(m)) {
            let _ = Command::new("bluetoothctl").args(["connect", mac]).output();
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(node: &str, bus: Option<&str>) -> DisabledEntry {
        DisabledEntry {
            node_name: node.into(),
            device_name: None,
            description: "x".into(),
            bus: bus.map(str::to_string),
            disabled_at: 0,
            output: false,
        }
    }

    #[test]
    fn parses_bluetoothctl_devices() {
        let out = "Device AA:BB:CC:DD:EE:FF WH-1000XM4\nDevice 11:22:33:44:55:66 Mouse\n";
        assert_eq!(parse_devices(out), ["AA:BB:CC:DD:EE:FF", "11:22:33:44:55:66"]);
    }

    #[test]
    fn empty_has_no_config() {
        assert_eq!(generate_config(&[]), None);
    }

    #[test]
    fn splits_alsa_and_bluez() {
        let conf = generate_config(&[
            entry("alsa_input.usb-Foo.analog-stereo", Some("usb")),
            entry("bluez_input.AA_BB.0", Some("bluetooth")),
        ])
        .unwrap();
        let alsa = conf.find("monitor.alsa.rules").unwrap();
        let bluez = conf.find("monitor.bluez.rules").unwrap();
        assert!(conf[alsa..bluez].contains("alsa_input.usb-Foo.analog-stereo"));
        assert!(conf[bluez..].contains("bluez_input.AA_BB.0"));
        assert!(conf.contains("node.disabled = true"));
    }

    #[test]
    fn escapes_quotes_and_backslashes() {
        let conf = generate_config(&[entry(r#"a"b\c"#, None)]).unwrap();
        assert!(conf.contains(r#"node.name = "a\"b\\c""#));
    }

    #[test]
    fn old_state_without_output_field_loads_as_input() {
        let json = br#"[{"node_name":"n","device_name":null,"description":"d","bus":null,"disabled_at":1}]"#;
        let e: Vec<DisabledEntry> = serde_json::from_slice(json).unwrap();
        assert!(!e[0].output);
    }

    #[test]
    fn entries_round_trip_through_json() {
        let e = vec![entry("n", Some("usb"))];
        let json = serde_json::to_vec(&e).unwrap();
        assert_eq!(serde_json::from_slice::<Vec<DisabledEntry>>(&json).unwrap(), e);
    }
}
